def test_upload_gcode_success_as_student(
    auth_client: TestClient,
    db_session: Session,
    auth_adapter: FakeAuthAdapter,
    storage_root: Path,
) -> None:
    user = _seed_profile(
        db_session=db_session,
        auth_adapter=auth_adapter,
        email=STUDENT_EMAIL,
        password=STUDENT_PASSWORD,
        role=UserRole.STUDENT,
    )
    token = _token(auth_client, STUDENT_EMAIL, STUDENT_PASSWORD)

    response = auth_client.post(
        "/api/jobs/upload",
        headers={"Authorization": f"Bearer {token}"},
        files={"file": ("my-part.gcode", SAMPLE_GCODE, "application/octet-stream")},
    )
    assert response.status_code == 201
    data = response.json()
    assert data["status"] == "pending_selection"
    assert data["original_filename"] == "my-part.gcode"
    assert data["gcode_path"] == f"{user.id}/{data['id']}.gcode"
    assert not data["gcode_path"].startswith("/")
    assert str(storage_root) not in data["gcode_path"]
    assert ".." not in data["gcode_path"]

    disk_path = storage_root / data["gcode_path"]
    assert disk_path.is_file()
    assert disk_path.read_bytes() == SAMPLE_GCODE

    job = db_session.get(PrintJob, UUID(data["id"]))
    assert job is not None
    assert job.status == JobStatus.PENDING_SELECTION
    assert job.material_id is None
    assert job.printer_id is None
    assert job.user_id == user.id
    assert job.original_filename == "my-part.gcode"
    assert job.gcode_path == data["gcode_path"]


