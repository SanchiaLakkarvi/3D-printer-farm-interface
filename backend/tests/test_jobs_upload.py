def test_upload_write_failure_cleans_up_no_job(
    auth_client: TestClient,
    db_session: Session,
    auth_adapter: FakeAuthAdapter,
    storage_root: Path,
) -> None:
    _seed_profile(
        db_session=db_session,
        auth_adapter=auth_adapter,
        email=STUDENT_EMAIL,
        password=STUDENT_PASSWORD,
        role=UserRole.STUDENT,
    )
    token = _token(auth_client, STUDENT_EMAIL, STUDENT_PASSWORD)
    leaky = OSError(f"Permission denied: {storage_root.resolve()}/blocked.gcode")

    with patch(
        "app.services.storage_service.write_bytes",
        side_effect=leaky,
    ):
        response = auth_client.post(
            "/api/jobs/upload",
            headers={"Authorization": f"Bearer {token}"},
            files={"file": ("write-fail.gcode", SAMPLE_GCODE, "application/octet-stream")},
        )

    assert response.status_code == 500
    assert response.json()["detail"]["code"] == "UPLOAD_FAILED"
    assert response.json()["detail"]["message"] == "Upload could not be completed"
    _assert_safe_error_payload(response, storage_root=storage_root)
    _assert_no_jobs(db_session)
    _assert_no_files(storage_root)


