def _assert_no_jobs(db_session: Session) -> None:
    assert list(db_session.scalars(select(PrintJob))) == []


def _assert_no_files(storage_root: Path) -> None:
    remaining = [p for p in storage_root.rglob("*") if p.is_file()]
    assert remaining == []


def _assert_safe_error_payload(response, *, storage_root: Path) -> None:
    """Failure responses must stay structured and must not leak host paths."""
    body = response.text
    assert str(storage_root) not in body
    assert str(storage_root.resolve()) not in body
    detail = response.json()["detail"]
    assert isinstance(detail, dict)
    assert "code" in detail and "message" in detail
    message = detail["message"]
    assert isinstance(message, str)
    assert str(storage_root) not in message
    assert "/Users/" not in message
    assert "Traceback" not in body
    assert "OSError" not in body
    assert "RuntimeError" not in body
    assert "Permission denied" not in body


def _seed_profile(
    *,
    db_session: Session,
    auth_adapter: FakeAuthAdapter,
    email: str,
    password: str,
    role: UserRole,
) -> User:
    user_id = auth_adapter.seed_user(email=email, password=password)
    user = User(
        id=user_id,
        email=email.lower(),
        first_name="Test",
        last_name="User",
        student_number=None,
        role=role,
        department=None,
        created_at=datetime.now(timezone.utc),
    )
    db_session.add(user)
    db_session.commit()
    return user


def _token(auth_client: TestClient, email: str, password: str) -> str:
    response = auth_client.post(
        "/api/auth/signin",
        json={"email": email, "password": password},
    )
    assert response.status_code == 200
    return response.json()["access_token"]


@pytest.fixture()
def storage_root(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    root = tmp_path / "storage"
    root.mkdir()
    monkeypatch.setattr(settings, "file_storage_root", str(root))
    return root


